-- Bookstore Case Study Database (MySQL 8.0+)
-- Synthetic dataset: 50 authors + 300 books + 400 customers + 1,200 orders = 1,950 rows
-- Run in MySQL Workbench/phpMyAdmin. Data is fictional and intended for SQL practice.
-- Note: The supplied Orders schema has one book_id per order. Therefore Q25 (books appearing together in the same order)
-- cannot be answered with this schema; use an OrderItems table or a multi-item order schema for that question.
CREATE DATABASE IF NOT EXISTS bookstore_case_study CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE bookstore_case_study;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS Orders;
DROP TABLE IF EXISTS Books;
DROP TABLE IF EXISTS Customers;
DROP TABLE IF EXISTS Authors;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE Authors (
    author_id INT PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    birth_year SMALLINT,
    nationality VARCHAR(80)
);
CREATE TABLE Books (
    book_id INT PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    author_id INT NOT NULL,
    publication_year SMALLINT,
    genre VARCHAR(80) NULL,
    price DECIMAL(10,2) NULL,
    stock INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_books_author FOREIGN KEY (author_id) REFERENCES Authors(author_id),
    CONSTRAINT chk_books_price CHECK (price IS NULL OR price > 0),
    CONSTRAINT chk_books_stock CHECK (stock >= 0)
);
CREATE TABLE Customers (
    customer_id INT PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(255) NULL,
    join_date DATE NOT NULL
);
CREATE TABLE Orders (
    order_id INT PRIMARY KEY,
    customer_id INT NOT NULL,
    book_id INT NOT NULL,
    order_date DATE NOT NULL,
    quantity INT NOT NULL,
    total_amount DECIMAL(10,2) NOT NULL,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES Customers(customer_id),
    CONSTRAINT fk_orders_book FOREIGN KEY (book_id) REFERENCES Books(book_id),
    CONSTRAINT chk_order_quantity CHECK (quantity > 0),
    CONSTRAINT chk_order_total CHECK (total_amount >= 0)
);

